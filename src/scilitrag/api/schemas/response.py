
"""
Response schemas for the SciLitRAG API.

These models convert internal pipeline results into a stable JSON
contract that frontend applications can consume.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field


class CitationResponse(BaseModel):
    """Represent a verified source passage from an indexed or uploaded paper."""

    model_config = ConfigDict(extra="forbid")

    evidence_id: str = Field(
        ...,
        description="Numeric source label used in the generated answer.",
        examples=["1"],
    )

    chunk_id: str = Field(
        ...,
        description="Unique identifier of the source passage.",
    )

    source_type: str = Field(
        default="arxiv",
        description="Source type: arxiv or upload.",
    )

    source_id: str | None = Field(
        default=None,
        description="Identifier of the source paper or uploaded document.",
    )

    arxiv_id: str | None = Field(
        default=None,
        description="arXiv identifier; null for uploaded documents.",
    )

    filename: str | None = Field(
        default=None,
        description="Original filename when the source is an uploaded document.",
    )

    title: str = Field(
        ...,
        description="Title of the source research document.",
    )

    page_number: int = Field(
        ...,
        ge=1,
        description="Page number containing the cited passage.",
    )

    text: str = Field(
        ...,
        description="Original evidence passage retrieved from the document.",
    )

    reranker_score: float = Field(
        ...,
        description="Cross-encoder relevance score; not a probability.",
    )


class PaperResponse(BaseModel):
    """Represent a research paper available in the SciLitRAG library."""

    model_config = ConfigDict(extra="forbid")

    arxiv_id: str = Field(
        ...,
        description="Versioned arXiv identifier of the paper.",
    )

    title: str = Field(
        ...,
        description="Full title of the research paper.",
    )

    authors: list[str] = Field(
        ...,
        description="Authors of the research paper.",
    )

    abstract: str = Field(
        ...,
        description="Abstract describing the research paper.",
    )

    published: str = Field(
        ...,
        description="Original publication timestamp in ISO 8601 format.",
    )

    categories: list[str] = Field(
        ...,
        description="All arXiv categories assigned to the paper.",
    )

    primary_category: str = Field(
        ...,
        description="Primary arXiv category of the paper.",
    )

    pdf_url: str = Field(
        ...,
        description="Public URL of the paper's PDF on arXiv.",
    )


class AskResponse(BaseModel):
    """Represent the complete result of a research question."""

    model_config = ConfigDict(extra="forbid")

    question: str = Field(
        ...,
        description="Original research question.",
    )

    answer: str = Field(
        ...,
        description="Generated answer grounded in retrieved evidence.",
    )

    citations: list[CitationResponse] = Field(
        default_factory=list,
        description="Verified evidence references used in the answer.",
    )

    context_token_count: int = Field(
        ...,
        ge=0,
        description="Number of tokens used by the assembled evidence context.",
    )

    generation_duration_seconds: float | None = Field(
        default=None,
        ge=0,
        description="Time spent generating the answer, in seconds.",
    )

    generation_token_count: int | None = Field(
        default=None,
        ge=0,
        description="Number of tokens generated by the language model.",
    )

    tokens_per_second: float | None = Field(
        default=None,
        ge=0,
        description="Measured language-model generation throughput.",
    )

    total_response_duration_seconds: float = Field(
        ...,
        ge=0,
        description=(
            "Total server-side request processing time, "
            "including inference and API response construction."
        ),
    )


class CompareResponse(BaseModel):
    """Represent a grounded comparison of selected research papers."""

    model_config = ConfigDict(extra="forbid")

    arxiv_ids: list[str] = Field(
        ...,
        min_length=2,
        max_length=3,
        description="arXiv IDs of the papers included in the comparison.",
    )

    answer: str = Field(
        ...,
        description=(
            "Generated comparison covering methodologies, findings, "
            "similarities, differences, and limitations."
        ),
    )

    citations: list[CitationResponse] = Field(
        default_factory=list,
        description="Verified evidence references supporting the comparison.",
    )

    context_token_count: int = Field(
        ...,
        ge=0,
        description="Number of tokens used by the assembled comparison context.",
    )

    generation_duration_seconds: float | None = Field(
        default=None,
        ge=0,
    )

    generation_token_count: int | None = Field(
        default=None,
        ge=0,
    )

    tokens_per_second: float | None = Field(
        default=None,
        ge=0,
    )

    total_response_duration_seconds: float = Field(
        ...,
        ge=0,
        description="Total server-side comparison processing time.",
    )


class UploadResponse(BaseModel):
    """Represent a successfully uploaded and extracted research PDF."""

    model_config = ConfigDict(extra="forbid")

    upload_id: str = Field(
        ...,
        description="Opaque identifier used to reference the uploaded document.",
    )

    filename: str = Field(
        ...,
        description="Sanitized original filename.",
    )

    title: str = Field(
        ...,
        description="Document title extracted from PDF metadata or filename.",
    )

    page_count: int = Field(
        ...,
        ge=1,
        description="Number of pages extracted from the uploaded PDF.",
    )

    total_characters: int = Field(
        ...,
        ge=1,
        description="Total number of characters extracted from the document.",
    )

    created_at: str = Field(
        ...,
        description="UTC timestamp indicating when the document was stored.",
    )
