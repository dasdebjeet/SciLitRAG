# Load and validate the existing benchmark before making any changes.
with benchmark_path.open(encoding="utf-8") as file:
    existing = [
        json.loads(line)
        for line in file
        if line.strip()
    ]

existing_ids = {item["question_id"] for item in existing}
new_ids = [item["question_id"] for item in new_questions]

# Prevent accidental overwrites or duplicate permanent question IDs.
if len(existing_ids) != len(existing):
    raise ValueError("Existing benchmark contains duplicate question IDs.")

if any(question_id in existing_ids for question_id in new_ids):
    raise ValueError("One or more new question IDs already exist.")

if new_ids != ["q012", "q013", "q014"]:
    raise ValueError("Unexpected permanent question ID sequence.")

# Create a backup before modifying the permanent benchmark.
shutil.copy2(benchmark_path, backup_path)

# Write the complete benchmark as one compact JSON object per line.
combined = existing + new_questions
temporary_path = benchmark_path.with_suffix(".jsonl.tmp")

with temporary_path.open("w", encoding="utf-8") as file:
    for question in combined:
        file.write(json.dumps(question, ensure_ascii=False) + "\n")

# Validate the newly written file before replacing the original.
with temporary_path.open(encoding="utf-8") as file:
    validated = [json.loads(line) for line in file if line.strip()]

if len(validated) != 14:
    temporary_path.unlink()
    raise ValueError("Expected exactly 14 benchmark questions.")

if len({item["question_id"] for item in validated}) != 14:
    temporary_path.unlink()
    raise ValueError("Duplicate question IDs detected after consolidation.")

temporary_path.replace(benchmark_path)

print(f"Backup created: {backup_path}")
print(f"Permanent benchmark updated: {len(validated)} questions")
print("New IDs:", ", ".join(new_ids))
